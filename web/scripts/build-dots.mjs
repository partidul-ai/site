// Builds src/data/dots.ts: Romania as a hex grid of dots, each dot tagged with its județ.
// Source: https://gisco-services.ec.europa.eu/distribution/v2/nuts/geojson/NUTS_RG_10M_2024_4326_LEVL_3.geojson
// © EuroGeographics for the administrative boundaries.
// Usage: node scripts/build-dots.mjs <path-to-geojson>
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) throw new Error('usage: node scripts/build-dots.mjs <nuts3.geojson>');

const WIDTH = 1000;
const STEP = 10.5; // dot spacing, in viewBox units
const PAD = 12;
const LAT0 = 46; // central latitude of Romania, for a simple equirectangular projection
const k = Math.cos((LAT0 * Math.PI) / 180);

const features = JSON.parse(readFileSync(src, 'utf8')).features.filter(
  (f) => f.properties.CNTR_CODE === 'RO',
);
const polygons = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates);

let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
for (const f of features)
  for (const poly of polygons(f.geometry))
    for (const ring of poly)
      for (const [lon, lat] of ring) {
        minX = Math.min(minX, lon * k); maxX = Math.max(maxX, lon * k);
        minY = Math.min(minY, -lat); maxY = Math.max(maxY, -lat);
      }

const scale = (WIDTH - 2 * PAD) / (maxX - minX);
const HEIGHT = Math.ceil((maxY - minY) * scale + 2 * PAD);
const toXY = ([lon, lat]) => [(lon * k - minX) * scale + PAD, (-lat - minY) * scale + PAD];
const toLatLon = (x, y) => [-((y - PAD) / scale + minY), ((x - PAD) / scale + minX) / k];

const shapes = features.map((f) => ({
  id: f.properties.NUTS_ID,
  rings: polygons(f.geometry).flat().map((ring) => ring.map(toXY)),
}));

// Even-odd ray casting over all rings, so holes (Ilfov around București) work.
function inside(x, y, rings) {
  let c = false;
  for (const r of rings)
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i], [xj, yj] = r[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
    }
  return c;
}

const ids = shapes.map((s) => s.id).sort();
const dots = [];
const ROW = STEP * Math.sqrt(3) / 2;
for (let row = 0, y = PAD / 2; y < HEIGHT; row++, y += ROW)
  for (let x = PAD / 2 + (row % 2 ? STEP / 2 : 0); x < WIDTH; x += STEP) {
    const s = shapes.find((s) => inside(x, y, s.rings));
    if (s) dots.push([Math.round(x * 10) / 10, Math.round(y * 10) / 10, ids.indexOf(s.id)]);
  }

// Small counties (București) can fall between grid points: guarantee each one a dot at its centre.
const centers = {};
for (const s of shapes) {
  const i = ids.indexOf(s.id);
  const own = dots.filter((d) => d[2] === i);
  let cx, cy;
  if (own.length) {
    cx = own.reduce((a, d) => a + d[0], 0) / own.length;
    cy = own.reduce((a, d) => a + d[1], 0) / own.length;
  } else {
    const pts = s.rings[0];
    cx = pts.reduce((a, p) => a + p[0], 0) / pts.length;
    cy = pts.reduce((a, p) => a + p[1], 0) / pts.length;
  }
  if (own.length < 3) {
    // Re-tag the nearest few grid dots so the county is visible and clickable.
    const near = dots
      .map((d) => [Math.hypot(d[0] - cx, d[1] - cy), d])
      .sort((a, b) => a[0] - b[0])
      .slice(0, 3);
    for (const [, d] of near) d[2] = i;
  }
  const [lat, lon] = toLatLon(cx, cy);
  centers[s.id] = [Math.round(lat * 100) / 100, Math.round(lon * 100) / 100];
}

const dest = fileURLToPath(new URL('../src/data/dots.ts', import.meta.url));
writeFileSync(
  dest,
  `// Generated by scripts/build-dots.mjs — do not edit.\n` +
    `// Boundaries © EuroGeographics (Eurostat GISCO, NUTS 2024).\n` +
    `export const DOT_VIEW = { width: ${WIDTH}, height: ${HEIGHT}, step: ${STEP} };\n` +
    `/** NUTS3 id for each county index used in DOTS. */\n` +
    `export const DOT_COUNTIES = ${JSON.stringify(ids)};\n` +
    `/** County centre as [lat, lon]. */\n` +
    `export const COUNTY_CENTERS: Record<string, [number, number]> = ${JSON.stringify(centers)};\n` +
    `/** Flat [x, y, countyIndex, x, y, countyIndex, …]. */\n` +
    `export const DOTS = new Float32Array(${JSON.stringify(dots.flat())});\n`,
);
const perCounty = ids.map((_, i) => dots.filter((d) => d[2] === i).length);
console.log(`${dots.length} dots, view ${WIDTH}x${HEIGHT}, min/county ${Math.min(...perCounty)}, ${(readFileSync(dest).length / 1024).toFixed(0)} KB`);
