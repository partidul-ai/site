// Builds src/data/outlines.ts: small outline paths of Romania and each județ, for icons.
// Source: Eurostat GISCO NUTS 2024, 1:20M (© EuroGeographics for the administrative boundaries):
//   https://gisco-services.ec.europa.eu/distribution/v2/nuts/geojson/NUTS_RG_20M_2024_4326_LEVL_0.geojson
//   https://gisco-services.ec.europa.eu/distribution/v2/nuts/geojson/NUTS_RG_20M_2024_4326_LEVL_3.geojson
// Usage: node scripts/build-outlines.mjs <level0.geojson> <level3.geojson>
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const [l0, l3] = process.argv.slice(2);
if (!l0 || !l3) throw new Error('usage: node scripts/build-outlines.mjs <nuts0.geojson> <nuts3.geojson>');

const BOX = 24; // each outline fills a 24×24 box, centered, aspect kept
const k = Math.cos((46 * Math.PI) / 180); // same projection as the dot map
const ro = (file) => JSON.parse(readFileSync(file, 'utf8')).features.filter((f) => f.properties.CNTR_CODE === 'RO');
const rings = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates).map((poly) => poly[0]); // outer rings

function path(geometry) {
  const pts = rings(geometry).map((r) => r.map(([lon, lat]) => [lon * k, -lat]));
  const all = pts.flat();
  const [x0, x1] = [Math.min(...all.map((p) => p[0])), Math.max(...all.map((p) => p[0]))];
  const [y0, y1] = [Math.min(...all.map((p) => p[1])), Math.max(...all.map((p) => p[1]))];
  const s = BOX / Math.max(x1 - x0, y1 - y0);
  const dx = (BOX - (x1 - x0) * s) / 2, dy = (BOX - (y1 - y0) * s) / 2;
  const r1 = (v) => Math.round(v * 10) / 10;
  return pts
    .map((ring) => 'M' + ring.map(([x, y]) => `${r1((x - x0) * s + dx)} ${r1((y - y0) * s + dy)}`).join('L') + 'Z')
    .join('');
}

const out = { RO: path(ro(l0)[0].geometry) };
for (const f of ro(l3)) out[f.properties.NUTS_ID] = path(f.geometry);

writeFileSync(
  fileURLToPath(new URL('../src/data/outlines.ts', import.meta.url)),
  `// Generated by scripts/build-outlines.mjs — do not edit.
// Boundaries © EuroGeographics (Eurostat GISCO, NUTS 2024, 1:20M).
/** SVG paths in a 0 0 ${BOX} ${BOX} box: "RO" for the country, NUTS3 ids for each județ. */
export const OUTLINES: Record<string, string> = ${JSON.stringify(out)};
`,
);
console.log('outlines:', Object.keys(out).length);
